def test_moved_writes_exact_shim_text(gen, repo, capsys):
    _write_map(gen, _mapping())
    assert gen.cmd_moved(None) == 0
    shim = (repo / COPY_MOD).read_bytes()
    assert shim == (
        b'"""Re-export shim: ``fakepkg.thing`` now lives in ``llm_kit.final.thing``.\n'
        b"\n"
        b"Generated by scripts/llm_kit_repoint.py (command ``moved``); do not edit. The\n"
        b"quarantined copy keeps this path importable until the quarantine is removed.\n"
        b'"""\n'
        b"\n"
        b"import sys\n"
        b"\n"
        b"import llm_kit.final.thing as _final\n"
        b"\n"
        b"# One module object under both names: patches, fakes and module state seen\n"
        b"# through the copy path are the final module's.\n"
        b"sys.modules[__name__] = _final\n"
    )
    assert _read_map(gen)["modules"][LEGACY_MOD]["copy_sha256"] == gen._sha(shim)
    assert "shims: 1; slices: 0" in capsys.readouterr().out


@pytest.mark.parametrize("state", ["shim", "slice"])
def test_moved_row_without_final_fails_loudly(gen, repo, state):
    _write_map(gen, _mapping(state=state, final=None))
    with pytest.raises(SystemExit) as exc:
        gen.cmd_moved(None)
    assert "must name its final module" in str(exc.value)
    assert not (repo / COPY_MOD).exists()


def test_moved_slice_rehashes_without_rewriting(gen, repo):
    sliced = b"# hand-written slice\n"
    (repo / COPY_MOD).write_bytes(sliced)
    _write_map(gen, _mapping(state="slice"))
    assert gen.cmd_moved(None) == 0
    assert (repo / COPY_MOD).read_bytes() == sliced
    assert _read_map(gen)["modules"][LEGACY_MOD]["copy_sha256"] == gen._sha(sliced)


