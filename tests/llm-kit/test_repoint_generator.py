"""Unit tests for scripts/llm_kit_repoint.py: moved shims and test_text_edits.

Every test drives the generator's functions on a synthetic repo under tmp_path
(a fake map, a fake legacy tree, a fake copy tree). Nothing touches the real
repository: the module-level paths are monkeypatched and the mirror and the
git file listing are replaced.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Optional

import pytest

from repoint import load_generator

LEGACY_PKG = "plugins/fake-kit/lib/fakepkg"
COPY_PKG = "plugins/llm-kit/lib/llm_kit/_copy/fakepkg"
LEGACY_MOD = f"{LEGACY_PKG}/thing.py"
COPY_MOD = f"{COPY_PKG}/thing.py"
FINAL = "llm_kit.final.thing"
THING_SRC = b"def thing():\n    return 1\n"


@pytest.fixture()
def gen():
    return load_generator()


def _mapping(state: str = "shim", final: Optional[str] = FINAL) -> dict[str, Any]:
    row: dict[str, Any] = {
        "copy": COPY_MOD, "state": state,
        "legacy_sha256": "0" * 64, "copy_sha256": "0" * 64,
    }
    if final is not None:
        row["final"] = final
    return {
        "packages": {"fakepkg": {
            "copy": "llm_kit._copy.fakepkg", "plugin": "fake-kit",
            "plugin_dir": "plugins/fake-kit", "lib_dir": "plugins/fake-kit/lib",
            "source_dir": LEGACY_PKG, "copy_dir": COPY_PKG,
        }},
        "dropped": [], "excluded": [], "data_files": [],
        "string_sites": {}, "test_site_overrides": {},
        "modules": {LEGACY_MOD: row},
        "test_text_edits": [],
    }


@pytest.fixture()
def repo(gen, tmp_path: Path, monkeypatch) -> Path:
    """A fake repo: legacy tree, map file, copy root; generator paths redirected."""
    (tmp_path / LEGACY_PKG).mkdir(parents=True)
    (tmp_path / LEGACY_MOD).write_bytes(THING_SRC)
    (tmp_path / COPY_PKG).mkdir(parents=True)
    monkeypatch.setattr(gen, "REPO", tmp_path)
    monkeypatch.setattr(gen, "MAP_PATH", tmp_path / "repoint-map.json")
    monkeypatch.setattr(gen, "COPY_ROOT", tmp_path / "plugins/llm-kit/lib/llm_kit/_copy")
    monkeypatch.setattr(gen, "PORTING_LEDGER", tmp_path / "ledger.json")
    monkeypatch.setattr(gen, "git_files",
                        lambda *paths: [LEGACY_MOD] if LEGACY_PKG in paths[0] else [])
    monkeypatch.setattr(gen, "build_copy", lambda mapping: {COPY_MOD: THING_SRC})
    monkeypatch.setattr(gen, "unclassified_sites", lambda mapping: [])
    monkeypatch.setattr(gen, "stale_sites", lambda mapping: [])
    monkeypatch.setattr(gen, "package_initializers", lambda mapping: [])
    # the mirror is not under test
    monkeypatch.setattr(gen, "load_dispositions", lambda: {})
    monkeypatch.setattr(gen, "build_mirror", lambda mapping, disp: {})
    monkeypatch.setattr(gen, "write_mirror", lambda files: None)
    return tmp_path


def _write_map(gen, mapping: dict[str, Any]) -> None:
    gen.dump_json(gen.MAP_PATH, mapping)


def _read_map(gen) -> dict[str, Any]:
    return json.loads(gen.MAP_PATH.read_text(encoding="utf-8"))


