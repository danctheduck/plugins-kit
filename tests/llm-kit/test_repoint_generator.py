def test_module_table_preserves_final(gen, repo):
    mapping = _mapping()
    mapping["modules"][LEGACY_MOD]["legacy_sha256"] = gen._sha(THING_SRC)
    table = gen.module_table(mapping, {COPY_MOD: THING_SRC})
    assert table[LEGACY_MOD]["final"] == FINAL
    assert table[LEGACY_MOD]["state"] == "shim"


def test_module_table_unmoved_row_has_no_final(gen, repo):
    table = gen.module_table(_mapping(state="unmoved", final=None), {COPY_MOD: THING_SRC})
    assert "final" not in table[LEGACY_MOD]


